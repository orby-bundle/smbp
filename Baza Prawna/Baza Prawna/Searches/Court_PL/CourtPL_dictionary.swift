import Foundation

// MARK: - Court Data Models
struct CourtInfo: Codable, Identifiable, Hashable {
    let id: Int
    let name: String
    let type: String
    
    enum CodingKeys: String, CodingKey {
        case id, name, type
    }
}

// MARK: - SearchablePickerOption Wrapper
struct CourtInfoPickerOption: SearchablePickerOption, Identifiable {
    let courtInfo: CourtInfo
    
    var id: String { String(courtInfo.id) }
    var displayName: String { courtInfo.name }
    var isActive: Bool { true }
}

extension CourtInfo {
    var pickerOption: CourtInfoPickerOption {
        CourtInfoPickerOption(courtInfo: self)
    }
}

